const TIER_KEYS = {
  bronze: 'tierBronze',
  silver: 'tierSilver',
  gold: 'tierGold',
  diamond: 'tierDiamond',
} as const satisfies Record<string, HudKey>;

export function tierKey(tier: keyof typeof TIER_KEYS): HudKey {
  return TIER_KEYS[tier];
}

